export function getDashboardSummary() {
  const sales = transactions.reduce((s, t) => s + t.amount, 0);
  const litresSold = transactions.reduce((s, t) => s + t.litres, 0);
  const pumpsOnline = pumps.filter((p) => p.status !== 'OFFLINE').length;
  const productSales = {};
  const paymentMix = {};
  transactions.forEach((t) => {
    productSales[t.product] = (productSales[t.product] || 0) + t.amount;
    paymentMix[t.payment] = (paymentMix[t.payment] || 0) + t.amount;
  });
  return {
    stationName: station.name,
    syncStatus: 'SYNCING',
    sales,
    litresSold: Math.round(litresSold * 10) / 10,
    pumpsOnline,
    pumpsTotal: pumps.length,
    productSales,
    paymentMix,
    variance: -2500,
    lastSyncAt: new Date().toISOString(),
  };
}

